let language = "en";
export function getLanguage() { return language; }
export function setLanguage(value) { language = value === "zh-CN" ? "zh-CN" : "en"; }
const patterns = Object.entries(english).filter(([key]) => key.includes("{0}")).map(([key, value]) => {
  const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return [new RegExp("^" + escaped.replace(/\\\{\d+\\\}/g, "(.*?)") + "$"), value];
});
export function t(text) {
  if (typeof text !== "string" || language === "zh-CN") return text;
  if (Object.hasOwn(english, text)) return english[text];
  for (const [pattern, value] of patterns) {
    const match = pattern.exec(text);
    if (match) return value.replace(/\{(\d+)\}/g, (_, index) => t(match[Number(index) + 1]));
  }
  if (text.includes("\n")) return text.split("\n").map(t).join("\n");
  return text;
}
export async function loadLanguage(storage) {
  try { setLanguage((await storage.get("language")).language); }
  catch { setLanguage("en"); }
  return language;
}
export async function saveLanguage(storage, value) {
  await storage.set({ language: value });
  setLanguage(value);
}
// Capture static text once, so switching back restores the original Chinese text.
export function staticTranslations(root) {
  const entries = [];
  const walk = node => {
    if (node.nodeType === 3 && /[\u3400-\u9fff]/.test(node.textContent)) {
      const raw = node.textContent;
      entries.push(() => { node.textContent = raw.replace(raw.trim(), t(raw.trim())); });
    }
    if (node.nodeType === 1) {
      if (["SCRIPT", "STYLE"].includes(node.tagName)) return;
      for (const name of ["aria-label", "title"]) {
        const raw = node.getAttribute(name);
        if (raw) entries.push(() => node.setAttribute(name, t(raw)));
      }
    }
    for (const child of node.childNodes || []) walk(child);
  };
  walk(root);
  return () => entries.forEach(apply => apply());
}
